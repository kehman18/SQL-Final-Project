/*
1. Which customers have generated total sales revenue above the average
revenue generated by an ordering customer?
*/

SELECT
 SC.CustomerID,
 COUNT(SOH.SalesOrderID) AS OrderCount,
 SUM(SOH.TotalDue) AS CustomerRevenue
FROM Sales_Customer AS SC
INNER JOIN Sales_SalesOrderHeader AS SOH
 ON SOH.CustomerID = SC.CustomerID
GROUP BY SC.CustomerID
HAVING SUM(soh.TotalDue) > (
 SELECT AVG(customer_totals.CustomerRevenue)
 FROM (
 SELECT SUM(TotalDue) AS CustomerRevenue
 FROM Sales_SalesOrderHeader
 GROUP BY CustomerID
 ) AS customer_totals
)
ORDER BY CustomerRevenue DESC;


/*
2. Which finished goods have on-hand inventory below the average total
inventory held per stocked product?
*/

SELECT
    PP.ProductID,
    PP.Name AS ProductName,
    PPC.Name AS CategoryName,
    SUM(
        CASE
            WHEN PPI.Quantity IS NULL THEN 0
            ELSE PPI.Quantity
        END
    ) AS OnHandQuantity
FROM Production_Product AS PP
LEFT JOIN Production_ProductInventory AS PPI
    ON PPI.ProductID = PP.ProductID
LEFT JOIN Production_ProductSubcategory AS PPS
    ON PPS.ProductSubcategoryID = PP.ProductSubcategoryID
LEFT JOIN Production_ProductCategory AS PPC
    ON PPC.ProductCategoryID = PPS.ProductCategoryID
WHERE PP.FinishedGoodsFlag = 1
GROUP BY PP.ProductID, PP.Name, PPC.Name
HAVING SUM(
    CASE
        WHEN PPI.Quantity IS NULL THEN 0
        ELSE PPI.Quantity
    END
) < (SELECT AVG(PPIST.TotalQuantity)
    FROM (
        SELECT
            SUM(PPI2.Quantity) AS TotalQuantity
        FROM Production_ProductInventory AS PPI2
        GROUP BY PPI2.ProductID) AS PPIST
)
ORDER BY OnHandQuantity, ProductName;


/*
3. Which customer accounts have never placed a sales order?
*/

SELECT
 SC.CustomerID,
 COALESCE(SS.Name, CONCAT(PP.FirstName, ' ', PP.LastName)) AS CustomerName,
 SC.PersonID,
 SC.StoreID
FROM Sales_Customer AS SC
LEFT JOIN Sales_SalesOrderHeader AS SOH
 ON SOH.CustomerID = SC.CustomerID
LEFT JOIN Person_Person AS PP
 ON PP.BusinessEntityID = SC.PersonID
LEFT JOIN Sales_Store AS SS
 ON SS.BusinessEntityID = SC.StoreID
WHERE SOH.SalesOrderID IS NULL
 AND SC.CustomerID NOT IN (
 SELECT SSOH.CustomerID
 FROM Sales_SalesOrderHeader AS SSOH
 WHERE SSOH.CustomerID IS NOT NULL
 )
ORDER BY CustomerName, SC.CustomerID;


/*
4. Which sales territories have total order revenue above the average
territory revenue?
*/

SELECT
 SST.TerritoryID,
 SST.Name AS TerritoryName,
 SST.Group AS TerritoryGroup,
 COUNT(SOH.SalesOrderID) AS OrderCount,
 SUM(SOH.TotalDue) AS TerritoryRevenue
FROM Sales_SalesTerritory AS SST
INNER JOIN Sales_SalesOrderHeader AS soh
 ON SOH.TerritoryID = SST.TerritoryID
GROUP BY SST.TerritoryID, SST.Name, SST.Group
HAVING SUM(SOH.TotalDue) > (
 SELECT AVG(territory_totals.TerritoryRevenue)
 FROM (
 SELECT SUM(TotalDue) AS TerritoryRevenue
 FROM Sales_SalesOrderHeader
 WHERE TerritoryID IS NOT NULL
 GROUP BY TerritoryID
 ) AS territory_totals
)     
ORDER BY TerritoryRevenue DESC;


/*
5. Which salespeople are below the average SalesYTD for their assigned
territory?
*/

SELECT
 SSP.BusinessEntityID AS SalesPersonID,
 CONCAT(PP.FirstName, ' ', PP.LastName) AS SalesPersonName,
 SST.Name AS TerritoryName,
 SSP.SalesYTD,
 SSP.SalesLastYear
FROM Sales_SalesPerson AS SSP
INNER JOIN Person_Person AS PP
 ON PP.BusinessEntityID = SSP.BusinessEntityID
INNER JOIN Sales_SalesTerritory AS SST
 ON SST.TerritoryID = SSP.TerritoryID
WHERE SSP.SalesYTD < (
 SELECT AVG(SSP2.SalesYTD)
 FROM Sales_SalesPerson AS SSP2
 WHERE SSP2.TerritoryID = SSP.TerritoryID
)
ORDER BY SST.Name, SSP.SalesYTD;


/*
6. Which product offers have a discount percentage above the average
discount for their product subcategory?
*/

SELECT
PP.ProductID,
PP.Name AS ProductName,
PSC.Name AS SubcategoryName,
SSO.Description AS OfferDescription,
SSO.DiscountPct
FROM Sales_SpecialOffer AS SSO
INNER JOIN Sales_SpecialOfferProduct AS SOP
ON SOP.SpecialOfferID = SSO.SpecialOfferID
INNER JOIN Production_Product AS PP
ON PP.ProductID = SOP.ProductID
INNER JOIN Production_ProductSubcategory AS PSC
ON PSC.ProductSubcategoryID = PP.ProductSubcategoryID
WHERE SSO.DiscountPct > (
SELECT AVG(SO2.DiscountPct)
FROM Sales_SpecialOffer AS SO2
INNER JOIN Sales_SpecialOfferProduct AS SOP2
ON SOP2.SpecialOfferID = SO2.SpecialOfferID
INNER JOIN Production_Product AS P2
ON P2.ProductID = SOP2.ProductID
WHERE P2.ProductSubcategoryID = PP.ProductSubcategoryID
)
ORDER BY PSC.Name, SSO.DiscountPct DESC, PP.Name;


/*
7. Which vendor-product pairs have a standard purchase price above the
average supplier price for that same product?
*/

SELECT
PPV.ProductID,
PP.Name AS ProductName,
PV.BusinessEntityID AS VendorID,
PV.Name AS VendorName,
PPV.StandardPrice,
PPV.MinOrderQty
FROM Purchasing_ProductVendor AS PPV
INNER JOIN Purchasing_Vendor AS PV
ON PV.BusinessEntityID = PPV.BusinessEntityID
INNER JOIN Production_Product AS PP
ON PP.ProductID = PPV.ProductID
WHERE PPV.StandardPrice > (
SELECT AVG(PPV2.StandardPrice)
FROM Purchasing_ProductVendor AS PPV2
WHERE PPV2.ProductID = PPV.ProductID
)
ORDER BY PP.Name, PPV.StandardPrice DESC;


/*
8. Which pending or approved purchase orders exceed the average open
purchase-order subtotal for their vendor?
*/

SELECT
PV.BusinessEntityID AS VendorID,
PV.Name AS VendorName,
POH.PurchaseOrderID,
POH.OrderDate,
POH.Status,
POH.SubTotal
FROM Purchasing_Vendor AS PV
RIGHT JOIN Purchasing_PurchaseOrderHeader AS POH
ON POH.VendorID = PV.BusinessEntityID
WHERE POH.Status IN (1, 2)
AND POH.SubTotal > (
SELECT AVG(POH2.SubTotal)
FROM Purchasing_PurchaseOrderHeader AS POH2
WHERE POH2.VendorID = POH.VendorID
AND POH2.Status IN (1, 2)
)
ORDER BY PV.Name, POH.SubTotal DESC;


/*
9. Which employees have a current hourly rate above the current average
rate in their department?
*/

SELECT
HRE.BusinessEntityID AS EmployeeID,
CONCAT(PP.FirstName, ' ', PP.LastName) AS EmployeeName,
HRD.Name AS DepartmentName,
EPH.Rate AS CurrentHourlyRate
FROM HumanResources_Employee AS HRE
INNER JOIN Person_Person AS PP
ON PP.BusinessEntityID = HRE.BusinessEntityID
INNER JOIN HumanResources_EmployeeDepartmentHistory AS EDH
ON EDH.BusinessEntityID = HRE.BusinessEntityID
AND EDH.EndDate IS NULL
INNER JOIN HumanResources_Department AS HRD
ON HRD.DepartmentID = EDH.DepartmentID
INNER JOIN HumanResources_EmployeePayHistory AS EPH
ON EPH.BusinessEntityID = HRE.BusinessEntityID
AND EPH.RateChangeDate = (
SELECT MAX(EPH0.RateChangeDate)
FROM HumanResources_EmployeePayHistory AS EPH0
WHERE EPH0.BusinessEntityID = HRE.BusinessEntityID
)
WHERE EPH.Rate > (
SELECT AVG(EPH2.Rate)
FROM HumanResources_EmployeePayHistory AS EPH2
INNER JOIN HumanResources_EmployeeDepartmentHistory AS EDH2
ON EDH2.BusinessEntityID = EPH2.BusinessEntityID
AND EDH2.EndDate IS NULL
WHERE EDH2.DepartmentID = EDH.DepartmentID
AND EPH2.RateChangeDate = (
SELECT MAX(EPH3.RateChangeDate)
FROM HumanResources_EmployeePayHistory AS EPH3
WHERE EPH3.BusinessEntityID = EPH2.BusinessEntityID
)
)
ORDER BY HRD.Name, CurrentHourlyRate DESC;


/*
10. Which individual-customer orders are larger than that customer's average
order value?
*/

